using System;
using Grasshopper2.Components;
using Grasshopper2.Parameters;
using Grasshopper2.UI;
using Grasshopper2.UI.Icon;
using GrasshopperIO;
using Pachyderm_Acoustic;
using Pachyderm_Acoustic.Environment;
using Rhino.Geometry;
using Grasshopper2.Data;
using System.Collections.Generic;

namespace PachydermGH
{
    [IoId("da2a5b17-adb4-4841-bd84-3d37fffbf5da")]
    public class RhinoSource_Component : Component
    {
        /// <summary>
        /// Initializes a new instance of the MyComponent1 class.
        /// </summary>
        public RhinoSource_Component()
          : base(new Nomen("Source From Rhino",
              "Pulls the source objects that have been defined in the Rhino Model",
              "Acoustics", "Model"))
        {
        }

        public RhinoSource_Component(IReader reader) : base(reader) { }

        /// <summary>
        /// Registers all the input parameters for this component.
        /// </summary>
        protected override void AddInputs(InputAdder inputs)
        {
        }

        /// <summary>
        /// Registers all the output parameters for this component.
        /// </summary>
        protected override void AddOutputs(OutputAdder outputs)
        {
            outputs.AddGeneric("Source", "Src", "Sources from the Rhino Model", Access.Tree);
        }

        /// <summary>
        /// This is the method that actually does the work.
        /// </summary>
        /// <param name="DA">The DA object is used to retrieve from inputs and store in outputs.</param>
        protected override void Process(IDataAccess access)
        {
            Pachyderm_Acoustic.Environment.Source[] S = Pachyderm_Acoustic.Utilities.RCPachTools.GetSource(0);
            access.SetTree(0,Garden.TreeFromList(S));
        }
    }
}